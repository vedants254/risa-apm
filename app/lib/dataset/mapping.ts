/**
 * The mapping from uploaded sheets to the canonical tables, and the deterministic code that
 * applies it to every row. The model (lib/dataset/ai.ts) only proposes a mapping; this module
 * validates it strictly and applies it. A mapping never contains data values, only names.
 *
 * Mapping JSON (what the model returns, after validation):
 * {
 *   "tables": {                       // every canonical table; source null = not in the file
 *     "daily_marketing": {
 *       "source": "Spend" | ["Jan", "Feb"] | null,
 *       "columns": { "activity_date": "Date", "marketing_spend_inr": "Spend (Rs)", "platform": { "constant": "ads" } }
 *     }, ...
 *   },
 *   "date_order": "auto" | "DMY" | "MDY" | "YMD",
 *   "values": { "person_type": { "Student": "external", "Volunteer": "staff" }, "checkin_result": { "Yes": "admitted" }, ... },
 *   "person_flags": [ { "column": "Email", "op": "ends_with", "value": "@risa.test", "person_type": "test" } ],
 *   "can_import": true, "reason": "",
 *   "assumptions": ["..."], "unmapped_columns": [{ "sheet": "People", "column": "City" }]
 * }
 * Missing ID columns are generated by the cleaning step; names and IDs are reconciled there too.
 */
import type { Param } from "../db";
import type { SourceSheet } from "./parse";
import {
  COLUMN_MEANING,
  NUMERIC_DATE_RE,
  RAW_TABLES,
  REQUIRED,
  TABLE_NAMES,
  VOCAB,
  VOCAB_FIELDS,
  coerce,
  type DateOrder,
  type TableName,
  type VocabKey,
} from "./schema";

export type ColumnRule = string | { constant: string | number | null };
export interface TableRule {
  source: string[];
  columns: Record<string, ColumnRule>;
}
export interface PersonFlag {
  column: string;
  op: "contains" | "equals" | "starts_with" | "ends_with";
  value: string;
  person_type: "external" | "internal" | "staff" | "test";
}
export interface DatasetMapping {
  tables: Partial<Record<TableName, TableRule>>;
  date_order: "auto" | DateOrder;
  values: Partial<Record<VocabKey, Record<string, string>>>;
  person_flags: PersonFlag[];
  can_import: boolean;
  reason: string;
  assumptions: string[];
  unmapped_columns: { sheet: string; column: string }[];
}

export type Row = Record<string, Param>;
export interface AppliedTable {
  table: TableName;
  sources: string[];
  rows: Row[];
  /** Source sheet and row behind each canonical row, for person flags on unmapped columns. */
  src: { sheet: SourceSheet; values: unknown[] }[];
  /** Unmapped source columns kept on this table as extra text columns (x_...). */
  extras: { column: string; header: string }[];
  /** Cells that could not be read as the column type (cleared to null). */
  badCells: number;
  badRows: number[];
}
export interface SideTable {
  name: string;
  sheet: string;
  columns: { column: string; header: string }[];
  rows: Param[][];
}

const key = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
/** Header match ignoring case, spaces and punctuation. */
export function findHeader(headers: string[], name: string): string | undefined {
  return headers.find((h) => h === name) ?? headers.find((h) => h.toLowerCase() === name.toLowerCase()) ?? headers.find((h) => key(h) === key(name));
}
export function slug(s: string, max = 48): string {
  const out = s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, max);
  return out || "col";
}

// ---------------------------------------------------------------------------
// Validation (hand-written: no schema library in the project)
// ---------------------------------------------------------------------------
const FLAG_OPS = ["contains", "equals", "starts_with", "ends_with"] as const;
const PERSON_TYPES = VOCAB.person_type as readonly string[];

/**
 * Check a proposed mapping against the canonical schema and the uploaded sheets. Sheet and
 * column names are resolved case-insensitively to the exact names in the file. Returns the
 * normalised mapping, or the list of problems (sent back to the model on retry).
 */
export function validateMapping(raw: unknown, sheets: SourceSheet[]): { mapping?: DatasetMapping; errors: string[] } {
  const errors: string[] = [];
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return { errors: ["The reply must be a JSON object."] };
  const r = raw as Record<string, unknown>;
  const sheetByName = (n: string) => sheets.find((s) => s.name === n) ?? sheets.find((s) => s.name.toLowerCase() === n.toLowerCase()) ?? sheets.find((s) => key(s.name) === key(n));

  const tables: Partial<Record<TableName, TableRule>> = {};
  const rt = r.tables;
  if (!rt || typeof rt !== "object" || Array.isArray(rt)) errors.push(`"tables" must be an object keyed by table name (${TABLE_NAMES.join(", ")}).`);
  else {
    for (const [t, v] of Object.entries(rt as Record<string, unknown>)) {
      const spec = RAW_TABLES.find((s) => s.table === t);
      if (!spec) {
        errors.push(`Unknown table "${t}". Use only: ${TABLE_NAMES.join(", ")}.`);
        continue;
      }
      if (v === null) continue;
      if (typeof v !== "object" || Array.isArray(v)) {
        errors.push(`tables.${t} must be an object with "source" and "columns".`);
        continue;
      }
      const tv = v as { source?: unknown; columns?: unknown };
      const srcList = tv.source === null || tv.source === undefined ? [] : Array.isArray(tv.source) ? tv.source : [tv.source];
      const source: SourceSheet[] = [];
      for (const s of srcList) {
        const sh = typeof s === "string" ? sheetByName(s) : undefined;
        if (!sh) errors.push(`tables.${t}.source: no sheet named ${JSON.stringify(s)}. Sheets: ${sheets.map((x) => x.name).join(", ")}.`);
        else if (!source.includes(sh)) source.push(sh);
      }
      if (!source.length) continue;
      const columns: Record<string, ColumnRule> = {};
      const cols = tv.columns;
      if (cols !== undefined && (typeof cols !== "object" || cols === null || Array.isArray(cols))) {
        errors.push(`tables.${t}.columns must be an object.`);
        continue;
      }
      for (const [c, rule] of Object.entries((cols ?? {}) as Record<string, unknown>)) {
        if (!(c in spec.columns)) {
          errors.push(`tables.${t}.columns: "${c}" is not a column of ${t}. Columns: ${Object.keys(spec.columns).join(", ")}.`);
          continue;
        }
        if (rule === null || rule === undefined || rule === "") continue;
        if (typeof rule === "string") {
          const hit = source.map((s) => findHeader(s.headers, rule)).find(Boolean);
          if (!hit) errors.push(`tables.${t}.columns.${c}: no column "${rule}" in ${source.map((s) => s.name).join(", ")}.`);
          else columns[c] = hit;
        } else if (typeof rule === "object" && !Array.isArray(rule) && "constant" in (rule as object)) {
          const k = (rule as { constant: unknown }).constant;
          if (k !== null && typeof k !== "string" && typeof k !== "number" && typeof k !== "boolean")
            errors.push(`tables.${t}.columns.${c}.constant must be a string, number or null.`);
          else columns[c] = { constant: typeof k === "boolean" ? String(k) : (k as string | number | null) };
        } else errors.push(`tables.${t}.columns.${c} must be a source column name or {"constant": value}.`);
      }
      tables[t as TableName] = { source: source.map((s) => s.name), columns };
    }
  }

  const dateOrder = r.date_order ?? "auto";
  if (!["auto", "YMD", "DMY", "MDY"].includes(String(dateOrder))) errors.push(`"date_order" must be one of auto, YMD, DMY, MDY.`);

  const values: DatasetMapping["values"] = {};
  if (r.values !== undefined && r.values !== null) {
    if (typeof r.values !== "object" || Array.isArray(r.values)) errors.push(`"values" must be an object.`);
    else
      for (const [k, m] of Object.entries(r.values as Record<string, unknown>)) {
        if (!(k in VOCAB)) {
          errors.push(`values: unknown field "${k}". Use: ${Object.keys(VOCAB).join(", ")}.`);
          continue;
        }
        if (!m || typeof m !== "object" || Array.isArray(m)) {
          errors.push(`values.${k} must map source values to allowed values.`);
          continue;
        }
        const vk = k as VocabKey;
        const allowed = VOCAB[vk] as readonly string[];
        const out: Record<string, string> = {};
        for (const [from, to] of Object.entries(m as Record<string, unknown>)) {
          const t = typeof to === "string" ? to.trim().toLowerCase() : "";
          if (VOCAB_FIELDS[vk].strict && !allowed.includes(t)) errors.push(`values.${k}["${from}"] = ${JSON.stringify(to)} is not allowed. Use one of: ${allowed.join(", ")}.`);
          else if (!t) errors.push(`values.${k}["${from}"] must be a string.`);
          else out[from] = t.replace(/[\s-]+/g, "_");
        }
        values[vk] = out;
      }
  }

  const flags: PersonFlag[] = [];
  if (r.person_flags !== undefined && r.person_flags !== null) {
    if (!Array.isArray(r.person_flags)) errors.push(`"person_flags" must be an array.`);
    else
      for (const [i, f] of (r.person_flags as unknown[]).entries()) {
        const o = (f ?? {}) as Record<string, unknown>;
        if (typeof o.column !== "string" || typeof o.value !== "string" || !o.value.trim()) errors.push(`person_flags[${i}] needs "column" and a non-empty "value".`);
        else if (!FLAG_OPS.includes(o.op as (typeof FLAG_OPS)[number])) errors.push(`person_flags[${i}].op must be one of ${FLAG_OPS.join(", ")}.`);
        else if (!PERSON_TYPES.includes(String(o.person_type))) errors.push(`person_flags[${i}].person_type must be one of ${PERSON_TYPES.join(", ")}.`);
        else flags.push({ column: o.column, op: o.op as PersonFlag["op"], value: o.value, person_type: o.person_type as PersonFlag["person_type"] });
      }
  }

  const strList = (v: unknown) => (Array.isArray(v) ? v.filter((x) => typeof x === "string").map((x) => String(x).slice(0, 300)) : []);
  const unmapped = Array.isArray(r.unmapped_columns)
    ? (r.unmapped_columns as unknown[])
        .map((u) => u as Record<string, unknown>)
        .filter((u) => u && typeof u.sheet === "string" && typeof u.column === "string")
        .map((u) => ({ sheet: String(u.sheet), column: String(u.column) }))
    : [];

  if (errors.length) return { errors };
  return {
    errors,
    mapping: {
      tables,
      date_order: dateOrder as DatasetMapping["date_order"],
      values,
      person_flags: flags,
      can_import: r.can_import !== false,
      reason: typeof r.reason === "string" ? r.reason.slice(0, 500) : "",
      assumptions: strList(r.assumptions).slice(0, 12),
      unmapped_columns: unmapped,
    },
  };
}

// ---------------------------------------------------------------------------
// Fast path: sheets already in the canonical shape (like the original workbook)
// ---------------------------------------------------------------------------
const nameKey = (s: string) => s.toLowerCase().replace(/[^a-z]/g, "");

/**
 * Build the mapping without the model when sheet and column names already match the canonical
 * tables. Extra columns are kept; missing optional columns stay empty. Falls back to the model
 * (returns null) when a required table or column is missing, when another sheet looks like a
 * renamed table, or when a categorical column holds values outside the vocabulary.
 */
export function fastPathMapping(sheets: SourceSheet[]): DatasetMapping | null {
  const tables: Partial<Record<TableName, TableRule>> = {};
  const used = new Set<SourceSheet>();
  for (const spec of RAW_TABLES) {
    const sh = sheets.find((s) => !used.has(s) && [nameKey(spec.sheet), nameKey(spec.table)].includes(nameKey(s.name)));
    if (!sh) continue;
    const columns: Record<string, ColumnRule> = {};
    for (const c of Object.keys(spec.columns)) {
      const h = sh.headers.find((x) => x.toLowerCase() === c);
      if (h) columns[c] = h;
    }
    for (const c of REQUIRED[spec.table as TableName] ?? []) if (!columns[c]) return null;
    // A sheet that shares only a few canonical names is not this table.
    if (Object.keys(columns).length < Math.ceil(Object.keys(spec.columns).length / 2)) return null;
    used.add(sh);
    tables[spec.table as TableName] = { source: [sh.name], columns };
  }
  if (!tables.daily_marketing || (!tables.registrations && !tables.people)) return null;
  const canonicalCols = new Set(RAW_TABLES.flatMap((s) => Object.keys(s.columns)));
  for (const s of sheets) {
    if (used.has(s)) continue;
    if (s.headers.filter((h) => canonicalCols.has(h.toLowerCase())).length >= 3) return null;
  }
  // Categorical values must already be in the vocabulary.
  for (const [k, f] of Object.entries(VOCAB_FIELDS)) {
    if (!f.strict) continue;
    const rule = tables[f.table]?.columns[f.column];
    if (typeof rule !== "string") continue;
    const sh = sheets.find((s) => s.name === tables[f.table]!.source[0])!;
    const i = sh.headers.indexOf(rule);
    const allowed = VOCAB[k as VocabKey] as readonly string[];
    for (const row of sh.rows) {
      const v = row[i];
      if (v === null || v === undefined || v === "") continue;
      if (!allowed.includes(String(v).trim().toLowerCase())) return null;
    }
  }
  return {
    tables,
    date_order: "auto",
    values: {},
    person_flags: [],
    can_import: true,
    reason: "",
    assumptions: [],
    unmapped_columns: [],
  };
}

