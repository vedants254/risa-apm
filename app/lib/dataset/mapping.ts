/** Day order for one source column: inferred from values above 12, else the mapping's hint, else DMY. */
export function detectDateOrder(values: unknown[], hint: DatasetMapping["date_order"]): DateOrder {
  let dmy = 0;
  let mdy = 0;
  for (const v of values) {
    if (typeof v !== "string") continue;
    const m = v.trim().match(NUMERIC_DATE_RE);
    if (!m) continue;
    if (Number(m[1]) > 12) dmy++;
    else if (Number(m[2]) > 12) mdy++;
  }
  if (dmy && !mdy) return "DMY";
  if (mdy && !dmy) return "MDY";
  if (dmy || mdy) return dmy >= mdy ? "DMY" : "MDY";
  return hint === "auto" ? "DMY" : hint;
}

/**
 * Apply a validated mapping to every row of the source sheets. Values are coerced to the
 * column types; unreadable cells become null and are counted. Unmapped columns of a sheet are
 * kept as extra text columns on the table that uses the sheet most; sheets no table uses come
 * back as side tables.
 */
export function applyMapping(
  sheets: SourceSheet[],
  mapping: DatasetMapping,
): { tables: Partial<Record<TableName, AppliedTable>>; sideTables: SideTable[] } {
  const bySheet = new Map(sheets.map((s) => [s.name, s]));
  // Which table "owns" each sheet's unmapped columns: the one mapping the most columns from it.
  const owner = new Map<string, { table: TableName; n: number }>();
  for (const [t, rule] of Object.entries(mapping.tables) as [TableName, TableRule][]) {
    const n = Object.values(rule.columns).filter((r) => typeof r === "string").length;
    for (const s of rule.source) if ((owner.get(s)?.n ?? -1) < n) owner.set(s, { table: t, n });
  }
  const usedHeaders = new Map<string, Set<string>>();
  for (const rule of Object.values(mapping.tables)) {
    for (const s of rule!.source) {
      const set = usedHeaders.get(s) ?? new Set<string>();
      for (const r of Object.values(rule!.columns)) if (typeof r === "string") set.add(r);
      usedHeaders.set(s, set);
    }
  }

  const out: Partial<Record<TableName, AppliedTable>> = {};
  for (const spec of RAW_TABLES) {
    const t = spec.table as TableName;
    const rule = mapping.tables[t];
    if (!rule || !rule.source.length) continue;
    const applied: AppliedTable = { table: t, sources: rule.source, rows: [], src: [], extras: [], badCells: 0, badRows: [] };
    const extraNames = new Set(Object.keys(spec.columns));
    for (const sName of rule.source) {
      const sh = bySheet.get(sName);
      if (!sh) continue;
      const plan = Object.entries(spec.columns).map(([c, type]) => {
        const r = rule.columns[c];
        if (r === undefined) return { c, type, kind: "none" as const };
        if (typeof r !== "string") return { c, type, kind: "constant" as const, value: r.constant };
        const i = sh.headers.indexOf(findHeader(sh.headers, r) ?? "");
        if (i < 0) return { c, type, kind: "none" as const };
        const order = type === "date" || type === "ts" ? detectDateOrder(sh.rows.map((row) => row[i]), mapping.date_order) : undefined;
        return { c, type, kind: "column" as const, i, order };
      });
      // Extra columns for this sheet's unmapped headers (only on the owning table).
      const extraIdx: { i: number; column: string }[] = [];
      if (owner.get(sName)?.table === t) {
        const used = usedHeaders.get(sName) ?? new Set();
        for (const [i, h] of sh.headers.entries()) {
          if (used.has(h)) continue;
          let col = `x_${slug(h, 40)}`;
          for (let k = 2; extraNames.has(col); k++) col = `x_${slug(h, 36)}_${k}`;
          extraNames.add(col);
          if (!applied.extras.some((e) => e.column === col)) applied.extras.push({ column: col, header: h });
          extraIdx.push({ i, column: col });
        }
      }
      for (const [n, values] of sh.rows.entries()) {
        const row: Row = {};
        let bad = false;
        for (const p of plan) {
          if (p.kind === "none") row[p.c] = null;
          else if (p.kind === "constant") {
            try {
              row[p.c] = coerce(p.value, p.type, "DMY");
            } catch {
              row[p.c] = null;
            }
          } else {
            try {
              row[p.c] = coerce(values[p.i], p.type, p.order);
            } catch {
              row[p.c] = null;
              applied.badCells++;
              bad = true;
            }
          }
        }
        for (const e of extraIdx) {
          const v = coerce(values[e.i], "text");
          row[e.column] = v === null ? null : String(v).slice(0, 2000);
        }
        if (bad && applied.badRows.length < 20) applied.badRows.push(n + 2);
        applied.rows.push(row);
        applied.src.push({ sheet: sh, values });
      }
    }
    out[t] = applied;
  }

  // Whole sheets no table uses become side tables, so their data stays queryable.
  const sideTables: SideTable[] = [];
  const usedSheets = new Set(Object.values(mapping.tables).flatMap((r) => r!.source));
  const taken = new Set<string>();
  for (const sh of sheets) {
    if (usedSheets.has(sh.name)) continue;
    let name = `x_${slug(sh.name, 40)}`;
    for (let k = 2; taken.has(name); k++) name = `x_${slug(sh.name, 36)}_${k}`;
    taken.add(name);
    const colNames = new Set<string>(["_rid"]);
    const columns = sh.headers.map((h) => {
      let c = slug(h, 48);
      if (/^\d/.test(c)) c = `c_${c}`;
      for (let k = 2; colNames.has(c); k++) c = `${slug(h, 44)}_${k}`;
      colNames.add(c);
      return { column: c, header: h };
    });
    sideTables.push({
      name,
      sheet: sh.name,
      columns,
      rows: sh.rows.map((r) => columns.map((_, i) => {
        const v = coerce(r[i], "text");
        return v === null ? null : String(v).slice(0, 2000);
      })),
    });
  }
  return { tables: out, sideTables };
}

/** Short description of the canonical schema, for the model prompt and docs. */
export function describeColumn(c: string): string {
  return COLUMN_MEANING[c] ?? "";
}
